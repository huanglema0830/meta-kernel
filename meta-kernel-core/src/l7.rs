//! # L7 · 执行层（多内核互联 + 修复执行）
//!
//! 定位（`docs/LAYER_ARCHITECTURE.md §2.1`）：**L7 = 执行层**——第一个"能对外产生写作用"的层，
//! 因此**必须是最克制的一层**。零（上层输出）＝ L6 交互后的个体内核；
//! 扰动 ＝ 另一个内核的场域（互联侧）／已确认的修复需求（执行侧）。**戒律：不侵**。
//!
//! 设计见 `docs/L7_EXECUTION_DESIGN.md`。本模块（v0.108）已实现**不需要用户确认**的部分：
//!
//! | 模块 | 内容 | 状态 |
//! |---|---|---|
//! | [`mesh`] | 多内核互联：发现 → 握手 → 交换（含"不侵"硬约束：交换白名单 / 坐标回映射 / 本端为主） | ✅ 已实现 |
//! | [`grade`] | 动作分级 T0–T3 与授权判定（不可回滚者降级为拒绝） | ✅ 已实现 |
//! | [`ledger`] | 动作账（哈希链记录，篡改可检出） | ✅ 已实现 |
//! | `repair`（修复执行） | 诊断 → 建议 → **用户确认** → 执行 → 验证 | ⏸ **待确认**（涉及 T2/T3 写操作；设计+方案对比见 `docs/L7_EXECUTION_DESIGN.md §8`） |
//!
//! **边界（诚实）**：本层不实现任何真实 IO；真实网络探测与系统写入由宿主负责。
//! "修复执行"之所以未实现，不是能力不足，而是**分级纪律**——它含写操作，需先经发起人确认。

pub mod grade;
