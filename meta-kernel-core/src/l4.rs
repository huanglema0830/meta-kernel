//! # L4 · 场域戒律判定引擎（应用框架·拒绝层 v0.002）
//!
//! 依据：发起人指令（内部 v0.002 / 对外 v0.01）——L4 判断场域变化（变量）是否符合
//! 场域自身内在节律，再决定是否允许进入 L5。
//! 核心理念：**戒律不是外部规则，而是场域自身变化的内在边界**。一切判定在内在完成。
//!
//! 模块：
//! - [`dimension`]：七维场域状态向量 `S = (t, f, a, φ, x, H, τ)` 与偏离计算
//! - [`threshold`]：黄金常数（0.618 = 黄金分割；1.618 = 1 / 0.618）
//! - [`l4_gate`]：戒律判定引擎（check_state 纯函数；不非时食 / 不捉持）
//! - [`l4_router`]：判定路由（通过 → 转发 L5；拒绝 → 丢弃，不缓存）
//!
//! 戒律表：
//! | 戒律 | 触发 | 含义 |
//! |---|---|---|
//! | 不非时食 | 7 维中任意 ≥3 维偏离基线 > 1.618 倍 | 场域"过量"——非时之食，拒绝 |
//! | 不捉持 | 7 维中任意 ≥3 维偏离基线 < 0.618 倍 | 场域"枯弱"——执取不足，拒绝 |
//!
//! 与三量对应：存量 = 基线向量（健康态）；变量 = 各维偏移；补充增量 = 偏移之因（L5 生成，
//! L4 不涉）。本层只处理"变量 × 存量"判定。
//! 望闻问切 = 四种场域探测角度（望=空间/拓扑；闻=频率/时间；问=相位/时间；切=幅度/熵/时间），
//! 统一由判定引擎处理，不分开调用。

pub mod dimension;
pub mod l4_gate;
pub mod l4_router;
pub mod threshold;
